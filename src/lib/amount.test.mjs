import assert from 'node:assert/strict'
import { cleanAmount, showAmount, groupExpr } from './amount.js'
assert.equal(showAmount('6500000'), '65,00,000')
assert.equal(showAmount('100'), '100')
assert.equal(showAmount('1000'), '1,000')
assert.equal(showAmount('12345678'), '1,23,45,678')
assert.equal(showAmount('6500000.5'), '65,00,000.5')
assert.equal(showAmount('1234.'), '1,234.')
assert.equal(showAmount(''), '')
assert.equal(showAmount(null), '')
assert.equal(showAmount('.5'), '0.5')
assert.equal(cleanAmount('65,00,000'), '6500000')
assert.equal(cleanAmount('1.234'), '1.23')
assert.equal(cleanAmount('1.2.3'), '1.23')
assert.equal(cleanAmount('007'), '7')
assert.equal(cleanAmount('abc'), '')
assert.equal(cleanAmount('₹ 5,000'), '5000')
assert.equal(groupExpr('65000+1200.5'), '65,000+1,200.5')
assert.equal(groupExpr('2500000×2'), '25,00,000×2')
assert.equal(groupExpr(''), '')
console.log('amount format ok')
